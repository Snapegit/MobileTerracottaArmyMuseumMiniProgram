    import multipleSelect from "@/components/momo-multipleSelect/momo-multipleSelect";
	export default {
		data() {
			return {
				cross:'',
				ruleForm: {
				chanpinmingcheng: '',
				chanpinleixing: '',
				shejiyuansu: '',
				zhuti: '',
				caizhi: '',
				tupian: '',
			        price: '0',
				},
				chanpinleixingOptions: [],
				chanpinleixingIndex: 0,
				// 登录用户信息
				user: {},
                ro:{
                   chanpinmingcheng : false,
                   chanpinleixing : false,
                   shejiyuansu : false,
                   zhuti : false,
                   caizhi : false,
                   tupian : false,
                   price : false,
                },
			}
		},
		components: {
			wPicker,
            xiaEditor,
            multipleSelect
		},
		watch:{
		},
		async onLoad(options) {
			let table = uni.getStorageSync("nowTable");
			// 获取用户信息
			let res = await this.$api.session(table);
			this.user = res.data;
			
			// ss读取


			// 下拉框
			res = await this.$api.option(`chanpinleixing`,`chanpinleixing`,{});
			this.chanpinleixingOptions = res.data;
            this.chanpinleixingOptions.unshift("请选择产品类型");

			// 如果有登录，获取登录后保存的userid
			this.ruleForm.userid = uni.getStorageSync("userid")
			if (options.refid) {
				// 如果上一级页面传递了refid，获取改refid数据信息
				this.ruleForm.refid = options.refid;
				this.ruleForm.nickname = uni.getStorageSync("nickname");
			}
			// 如果是更新操作
			if (options.id) {
				this.ruleForm.id = options.id;
				// 获取信息
				res = await this.$api.info(`wenchuangchanpin`, this.ruleForm.id);
				this.ruleForm = res.data;
			}
			// 跨表
			this.cross = options.cross;
			if(options.cross){
				var obj = uni.getStorageSync('crossObj');
				for (var o in obj){
					if(o=='chanpinmingcheng'){
					this.ruleForm.chanpinmingcheng = obj[o];
					this.ro.chanpinmingcheng = true;
					continue;
					}
					if(o=='chanpinleixing'){
					this.ruleForm.chanpinleixing = obj[o];
					this.ro.chanpinleixing = true;
					continue;
					}
					if(o=='shejiyuansu'){
					this.ruleForm.shejiyuansu = obj[o];
					this.ro.shejiyuansu = true;
					continue;
					}
					if(o=='zhuti'){
					this.ruleForm.zhuti = obj[o];
					this.ro.zhuti = true;
					continue;
					}
					if(o=='caizhi'){
					this.ruleForm.caizhi = obj[o];
					this.ro.caizhi = true;
					continue;
					}
					if(o=='tupian'){
					this.ruleForm.tupian = obj[o].split(",")[0];
					this.ro.tupian = true;
					continue;
					}
					if(o=='price'){
					this.ruleForm.price = obj[o];
					this.ro.price = true;
					continue;
					}
				}
			}
			this.styleChange()
            this.$forceUpdate()
		},
		methods: {
			styleChange() {
				this.$nextTick(()=>{
					document.querySelectorAll('.radioText').forEach(el => {
					  el.removeAttribute('style')
					  const icon = {"color":"#666666"}
					  Object.keys(icon).forEach((key) => {
						el.style[key] = icon[key]
					  })
					})
					document.querySelectorAll('.radioTextActive').forEach(el => {
					  el.removeAttribute('style')
					  const icon = {"color":"#ff9933"}
					  Object.keys(icon).forEach((key) => {
						el.style[key] = icon[key]
					  })
					})
					document.querySelectorAll('.checkText').forEach(el => {
					  el.removeAttribute('style')
					  const icon = {"color":"#666666"}
					  Object.keys(icon).forEach((key) => {
						el.style[key] = icon[key]
					  })
					})
					document.querySelectorAll('.checkTextActive').forEach(el => {
					  el.removeAttribute('style')
					  const icon = {"color":"#ff9933"}
					  Object.keys(icon).forEach((key) => {
						el.style[key] = icon[key]
